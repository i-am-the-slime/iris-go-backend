// Generates go-ffi/Dhall.Parser/grammar.go, the Go tables of the nearley grammar in dhall/grammar.ne
// that Dhall.Parser's foreign module parses with in JavaScript.
//
//   bun dhall-parser/generate.ts
//
// nearleyc compiles the grammar; this script loads the compiled rules and writes each one as Go:
// its name, its symbols (a nonterminal, or a terminal as the UTF-16 code units it accepts, found by
// testing every code unit against the JavaScript regular expression) and its postprocessor. The
// postprocessors are JavaScript functions, ported by hand in go-ffi/Dhall.Parser/postprocess.go.
// Each one is recognised here by its source text, so that a grammar edit that changes or adds a
// postprocessor fails the generation until its Go port is written.

import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const compat = join(dirname(new URL(import.meta.url).pathname), "..");
const output = join(compat, "go-ffi/Dhall.Parser/grammar.go");

type Symbol = string | { literal: string } | RegExp;
type Rule = { name: string; symbols: Symbol[]; postprocess?: Function };

const names: string[] = [];
const nameIds = new Map<string, number>();
const unported: string[] = [];

function main() {
  const compiled = compileGrammar();
  const grammar = createRequire(import.meta.url)(compiled) as { ParserRules: Rule[]; ParserStart: string };
  const postprocessorSources = postprocessorSourcesOf(readFileSync(compiled, "utf8"), grammar.ParserRules.length);
  for (const rule of grammar.ParserRules) {
    if (!nameIds.has(rule.name)) {
      nameIds.set(rule.name, names.length);
      names.push(rule.name);
    }
  }
  const lines = grammar.ParserRules.map((rule, index) => {
    const symbols = rule.symbols.map(goSymbol).join(", ");
    const postprocess = goPostprocessor(postprocessorSources[index], rule.name);
    return `\t// ${describe(rule)}\n\t{name: ${nameIds.get(rule.name)}, symbols: []symbol{${symbols}}, postprocess: ${postprocess}},`;
  });
  if (unported.length > 0) {
    console.error(`postprocessors without a Go port (add them to postprocess.go and to \`ported\`):\n${unported.join("\n")}`);
    process.exit(1);
  }
  writeFileSync(output, goSource(grammar.ParserStart, lines));
  Bun.spawnSync(["gofmt", "-w", output], { stdio: ["inherit", "inherit", "inherit"] });
  console.log(`wrote ${output}: ${grammar.ParserRules.length} rules, ${names.length} nonterminals`);
}

function goSource(start: string, lines: string[]): string {
  return `// Code generated by dhall-parser/generate.ts from dhall/grammar.ne; DO NOT EDIT.

package Dhall_Parser_ffi

import "math"

// start is the rule a parse derives, ${start}.
const start = ${nameIds.get(start)}

// ruleNames are the nonterminals, indexed by the numbers the rules use.
var ruleNames = [...]string{
${names.map((name) => `\t${JSON.stringify(name)},`).join("\n")}
}

// rules are nearley's ParserRules in their order, which decides the order of the parses.
var rules = [...]rule{
${lines.join("\n")}
}
`;
}

function compileGrammar(): string {
  const target = join(mkdtempSync(join(tmpdir(), "dhall-grammar-")), "grammar.cjs");
  const nearleyc = join(compat, "node_modules/.bin/nearleyc");
  const compiling = Bun.spawnSync(["bun", nearleyc, join(compat, "dhall/grammar.ne"), "-o", target]);
  if (compiling.exitCode !== 0) {
    console.error(compiling.stderr.toString());
    process.exit(1);
  }
  return target;
}

// The source text of each rule's postprocessor, in rule order. Helpers such as `tag("Field")` are
// closures whose own source does not say which helper made them, so the text comes from the
// compiled grammar rather than from Function.prototype.toString.
function postprocessorSourcesOf(source: string, count: number): (string | undefined)[] {
  const body = source.slice(source.indexOf("ParserRules: ["), source.indexOf("ParserStart"));
  const segments = body.split(/\n    \{"name": /).slice(1);
  if (segments.length !== count) throw new Error(`found ${segments.length} rule texts for ${count} rules`);
  return segments.map((segment) => {
    const at = segment.indexOf('"postprocess":');
    if (at < 0) return undefined;
    return segment
      .slice(at + '"postprocess":'.length)
      .replace(/\}\s*,?\s*\]?,?\s*$/, "")
      .replace(/\s+/g, " ")
      .trim();
  });
}

function goSymbol(symbol: Symbol): string {
  if (typeof symbol === "string") return `nonterminal(${nameIds.get(symbol)})`;
  if (symbol instanceof RegExp) return `units(${unitRanges(symbol).join(", ")})`;
  if (symbol.literal.length !== 1) throw new Error(`literal ${JSON.stringify(symbol.literal)} is not one code unit`);
  return `literal(${hex(symbol.literal.charCodeAt(0))})`;
}

// The code units a terminal accepts, as inclusive lower and upper bounds.
function unitRanges(pattern: RegExp): string[] {
  const bounds: string[] = [];
  let low = -1;
  for (let unit = 0; unit <= 0x10000; unit++) {
    const accepted = unit < 0x10000 && pattern.test(String.fromCharCode(unit));
    if (accepted && low < 0) low = unit;
    if (!accepted && low >= 0) {
      bounds.push(hex(low), hex(unit - 1));
      low = -1;
    }
  }
  return bounds;
}

function hex(unit: number): string {
  return `0x${unit.toString(16).toUpperCase().padStart(2, "0")}`;
}

function describe(rule: Rule): string {
  const symbols = rule.symbols.map((symbol) =>
    typeof symbol === "string" ? symbol : symbol instanceof RegExp ? symbol.toString() : JSON.stringify(symbol.literal),
  );
  return `${rule.name} → ${symbols.join(" ")}`.replace(/[\u0000-\u001f\u007f-\u009f\ud800-\udfff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

function goPostprocessor(source: string | undefined, rule: string): string {
  if (source === undefined) return "nil";
  const helper = goHelper(source);
  if (helper !== undefined) return helper;
  const port = ported.get(source);
  if (port === undefined) {
    unported.push(`  ${rule}: ${source}`);
    return "nil";
  }
  return port;
}

// The grammar's own helpers and nearley's EBNF postprocessors.
function goHelper(source: string): string | undefined {
  const pass = /^pass(\d+)$/.exec(source) ?? /^pass\((\d+)\)$/.exec(source);
  if (pass) return `pass(${pass[1]})`;
  const tag = /^tag\(("\w+")\)$/.exec(source);
  if (tag) return `tag(${tag[1]})`;
  const binop = /^binop\(("\w+")(?:, (\d+))?(?:, (true|false))?\)$/.exec(source);
  if (binop) return `binop(${binop[1]}, ${binop[2] ?? 1}, ${binop[3] ?? false})`;
  return new Map([
    ["collapse", "collapse"],
    ["nuller", "nuller"],
    ["id", "id"],
    ["function joiner(d) {return d.join('');}", "joiner"],
    ["function arrpush(d) {return d[0].concat([d[1]]);}", "arrpush"],
    ["function(d) {return null;}", "nuller"],
  ]).get(source);
}

